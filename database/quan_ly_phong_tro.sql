--  Dữ liệu mẫu được tạo sẵn với tính nhất quán giữa các bảng:
--    - Phòng 'Đang thuê' đều có đúng 1 hợp đồng 'Còn hiệu lực'
--    - Tổng tiền hóa đơn = tiền phòng + tiền điện + tiền nước + tiền dịch vụ
--    - Hóa đơn 'Đã thanh toán' đều có 1 bản ghi thanh toán tương ứng
