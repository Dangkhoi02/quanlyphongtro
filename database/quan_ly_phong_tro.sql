SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP DATABASE IF EXISTS quan_ly_phong_tro;
CREATE DATABASE quan_ly_phong_tro CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE quan_ly_phong_tro;

-- ---------------------------------------------------------------------
-- 1. TẠO BẢNG
-- ---------------------------------------------------------------------
CREATE TABLE chu_tro (
  ma_chu     INT PRIMARY KEY AUTO_INCREMENT,
  ho_ten     VARCHAR(100) NOT NULL,
  sdt        VARCHAR(15)  NOT NULL UNIQUE,
  email      VARCHAR(100),
  cccd       VARCHAR(12)  NOT NULL UNIQUE
);

CREATE TABLE nha_tro (
  ma_nha     INT PRIMARY KEY AUTO_INCREMENT,
  ma_chu     INT NOT NULL,
  ten_nha    VARCHAR(100) NOT NULL,
  dia_chi    VARCHAR(200) NOT NULL,
  quan_huyen VARCHAR(50),
  so_tang    INT NOT NULL DEFAULT 1,
  FOREIGN KEY (ma_chu) REFERENCES chu_tro(ma_chu)
);

CREATE TABLE loai_phong (
  ma_loai     INT PRIMARY KEY AUTO_INCREMENT,
  ten_loai    VARCHAR(50) NOT NULL,
  dien_tich   INT NOT NULL,             -- m2
  gia_co_ban  DECIMAL(12,0) NOT NULL,   -- VND/tháng
  mo_ta       VARCHAR(200)
);

CREATE TABLE phong (
  ma_phong    INT PRIMARY KEY AUTO_INCREMENT,
  ma_nha      INT NOT NULL,
  ma_loai     INT NOT NULL,
  so_phong    VARCHAR(10) NOT NULL,
  tang        INT NOT NULL,
  gia_thue    DECIMAL(12,0) NOT NULL,   -- VND/tháng
  trang_thai  VARCHAR(20) NOT NULL DEFAULT 'Trống'
              CHECK (trang_thai IN ('Trống','Đang thuê','Bảo trì')),
  UNIQUE (ma_nha, so_phong),
  FOREIGN KEY (ma_nha)  REFERENCES nha_tro(ma_nha),
  FOREIGN KEY (ma_loai) REFERENCES loai_phong(ma_loai)
);

CREATE TABLE khach_thue (
  ma_khach    INT PRIMARY KEY AUTO_INCREMENT,
  ho_ten      VARCHAR(100) NOT NULL,
  gioi_tinh   VARCHAR(5)   NOT NULL CHECK (gioi_tinh IN ('Nam','Nữ')),
  ngay_sinh   DATE,
  sdt         VARCHAR(15)  NOT NULL UNIQUE,
  email       VARCHAR(100),
  cccd        VARCHAR(12)  NOT NULL UNIQUE,
  que_quan    VARCHAR(100),
  nghe_nghiep VARCHAR(100)
);

CREATE TABLE dich_vu (
  ma_dv    INT PRIMARY KEY AUTO_INCREMENT,
  ten_dv   VARCHAR(50) NOT NULL,
  don_gia  DECIMAL(12,0) NOT NULL,
  don_vi   VARCHAR(20) NOT NULL
);

CREATE TABLE hop_dong (
  ma_hd         INT PRIMARY KEY AUTO_INCREMENT,
  ma_phong      INT NOT NULL,
  ma_khach      INT NOT NULL,
  ngay_bat_dau  DATE NOT NULL,
  ngay_ket_thuc DATE NOT NULL,
  tien_coc      DECIMAL(12,0) NOT NULL,
  gia_thue      DECIMAL(12,0) NOT NULL,
  trang_thai    VARCHAR(20) NOT NULL
                CHECK (trang_thai IN ('Còn hiệu lực','Hết hạn','Đã hủy')),
  FOREIGN KEY (ma_phong) REFERENCES phong(ma_phong),
  FOREIGN KEY (ma_khach) REFERENCES khach_thue(ma_khach),
  CHECK (ngay_ket_thuc > ngay_bat_dau)
);

CREATE TABLE hoa_don (
  ma_hoa_don    INT PRIMARY KEY AUTO_INCREMENT,
  ma_hd         INT NOT NULL,
  nam           INT NOT NULL,
  thang         INT NOT NULL CHECK (thang BETWEEN 1 AND 12),
  tien_phong    DECIMAL(12,0) NOT NULL,
  so_dien_cu    INT NOT NULL,
  so_dien_moi   INT NOT NULL,
  so_nuoc_cu    INT NOT NULL,
  so_nuoc_moi   INT NOT NULL,
  tien_dien     DECIMAL(12,0) NOT NULL,
  tien_nuoc     DECIMAL(12,0) NOT NULL,
  tien_dich_vu  DECIMAL(12,0) NOT NULL,
  tong_tien     DECIMAL(12,0) NOT NULL,
  han_thanh_toan DATE NOT NULL,
  trang_thai    VARCHAR(20) NOT NULL
                CHECK (trang_thai IN ('Đã thanh toán','Chưa thanh toán','Quá hạn')),
  UNIQUE (ma_hd, nam, thang),
  FOREIGN KEY (ma_hd) REFERENCES hop_dong(ma_hd)
);

CREATE TABLE thanh_toan (
  ma_tt            INT PRIMARY KEY AUTO_INCREMENT,
  ma_hoa_don       INT NOT NULL,
  ngay_thanh_toan  DATE NOT NULL,
  so_tien          DECIMAL(12,0) NOT NULL,
  phuong_thuc      VARCHAR(30) NOT NULL,
  FOREIGN KEY (ma_hoa_don) REFERENCES hoa_don(ma_hoa_don)
);

